import PDFDocument from "pdfkit";
import { NextResponse } from "next/server";
import { getAdminClient } from "../../../../lib/supabase/admin";

export const runtime = "nodejs";

const documentTypes = {
  "purchase-orders": "purchase_order",
  rfqs: "rfq",
  invoices: "invoice",
};

const customerSelection =
  "id, name, slug, contact_name, email, whatsapp_phone, billing_address, notes, status, created_at";
const documentSelection =
  "id, organization_id, document_type, document_number, amount_idr, issued_at, due_at, status, notes";
const uuidPattern = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

function documentTitle(type) {
  if (type === "purchase_order") return "PURCHASE ORDER";
  if (type === "rfq") return "REQUEST FOR QUOTATION";
  if (type === "invoice") return "INVOICE";
  return "CUSTOMER PROFILE";
}

function printable(value) {
  return String(value ?? "—").replace(/\s+/g, " ").trim() || "—";
}

function formatMoney(value) {
  if (value === null || value === undefined) return "Not specified";
  return new Intl.NumberFormat("id-ID", {
    style: "currency",
    currency: "IDR",
    maximumFractionDigits: 0,
  }).format(value);
}

function createPdf({ title, reference, customer, fields }) {
  return new Promise((resolve, reject) => {
    const pdf = new PDFDocument({ size: "A4", margin: 52, bufferPages: true });
    const chunks = [];
    pdf.on("data", (chunk) => chunks.push(chunk));
    pdf.on("end", () => resolve(Buffer.concat(chunks)));
    pdf.on("error", reject);

    pdf.fillColor("#153353").fontSize(18).font("Helvetica-Bold").text("PT Outjourney");
    pdf.moveDown(0.35);
    pdf.fillColor("#6b7787").fontSize(9).font("Helvetica").text("B2B Food Supply");
    pdf.moveDown(1.7);
    pdf.fillColor("#17385e").fontSize(17).font("Helvetica-Bold").text(title);
    if (reference) {
      pdf.moveDown(0.3);
      pdf.fillColor("#5e6d80").fontSize(10).font("Helvetica").text(`Reference: ${printable(reference)}`);
    }

    pdf.moveDown(1.2);
    pdf.strokeColor("#dce3eb").moveTo(52, pdf.y).lineTo(543, pdf.y).stroke();
    pdf.moveDown(1);
    pdf.fillColor("#17385e").fontSize(11).font("Helvetica-Bold").text("CUSTOMER");
    pdf.moveDown(0.55);
    const customerFields = [
      ["Business name", customer.name],
      ["Contact person", customer.contact_name],
      ["Email", customer.email],
      ["WhatsApp", customer.whatsapp_phone],
      ["Billing address", customer.billing_address],
    ];
    customerFields.forEach(([label, value]) => addPdfField(pdf, label, value));

    pdf.moveDown(1.2);
    pdf.strokeColor("#dce3eb").moveTo(52, pdf.y).lineTo(543, pdf.y).stroke();
    pdf.moveDown(1);
    pdf.fillColor("#17385e").fontSize(11).font("Helvetica-Bold").text("DETAILS");
    pdf.moveDown(0.55);
    fields.forEach(([label, value]) => addPdfField(pdf, label, value));

    pdf.moveDown(2);
    pdf.fillColor("#7b8795").fontSize(8).font("Helvetica")
      .text("Generated by Outjourney. Please contact your account representative for questions.", { align: "center" });
    pdf.end();
  });
}

function addPdfField(pdf, label, value) {
  const startY = pdf.y;
  pdf.fillColor("#6b7787").fontSize(9).font("Helvetica").text(label, 52, startY, { width: 145 });
  pdf.fillColor("#26384f").fontSize(9).font("Helvetica-Bold").text(printable(value), 205, startY, { width: 338 });
  pdf.moveDown(0.8);
}

function safeFilename(value) {
  return printable(value)
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-zA-Z0-9_-]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80) || "record";
}

export async function GET(request) {
  const access = await getAdminClient();
  if (access.response) return access.response;

  const parameters = new URL(request.url).searchParams;
  const resource = parameters.get("resource") || "";
  const id = parameters.get("id") || "";
  if (!["customers", ...Object.keys(documentTypes)].includes(resource) || !uuidPattern.test(id)) {
    return NextResponse.json({ error: "Choose a valid customer or document record." }, { status: 400 });
  }

  try {
    let customer;
    let record;
    if (resource === "customers") {
      const { data, error } = await access.client
        .from("organizations")
        .select(customerSelection)
        .eq("id", id)
        .maybeSingle();
      if (error) throw error;
      customer = data;
      if (!customer) return NextResponse.json({ error: "Customer record not found." }, { status: 404 });
      record = customer;
    } else {
      const { data, error } = await access.client
        .from("crm_documents")
        .select(documentSelection)
        .eq("id", id)
        .eq("document_type", documentTypes[resource])
        .maybeSingle();
      if (error) throw error;
      if (!data) return NextResponse.json({ error: "Document record not found." }, { status: 404 });
      record = data;

      const { data: customerData, error: customerError } = await access.client
        .from("organizations")
        .select(customerSelection)
        .eq("id", record.organization_id)
        .maybeSingle();
      if (customerError) throw customerError;
      if (!customerData) return NextResponse.json({ error: "The document's customer record was not found." }, { status: 404 });
      customer = customerData;
    }

    const title = documentTitle(record.document_type);
    const fields = resource === "customers"
      ? [
          ["Customer slug", record.slug],
          ["Status", record.status],
          ["Notes", record.notes],
        ]
      : [
          ["Document number", record.document_number],
          ["Issued date", record.issued_at],
          ["Due date", record.due_at],
          ["Amount", formatMoney(record.amount_idr)],
          ["Status", record.status],
          ["Notes", record.notes],
        ];
    const bytes = await createPdf({ title, reference: record.document_number, customer, fields });
    const filename = `outjourney-${safeFilename(record.document_number || customer.name)}.pdf`;
    return new NextResponse(bytes, {
      headers: {
        "Content-Type": "application/pdf",
        "Content-Disposition": `attachment; filename="${filename}"`,
        "Cache-Control": "no-store",
      },
    });
  } catch (error) {
    console.error("Could not generate an Outjourney CRM PDF.", error);
    return NextResponse.json({ error: "Could not generate this PDF. Please try again." }, { status: 500 });
  }
}
